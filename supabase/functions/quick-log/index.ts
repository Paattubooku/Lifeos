// POST /functions/v1/quick-log/water   {"ml": 500}
// POST /functions/v1/quick-log/expense {"amount": 240, "category"?, "payee"?, "note"?}
// Authorization: Bearer lifeos_pat_…   (iPhone Shortcuts / Siri, PRD F19)
import { quickLogRow } from '../_shared/ingest.ts';
import { admin, authenticate, categoriesOf, json, readJson } from '../_shared/server.ts';

Deno.serve(async (req) => {
  if (req.method !== 'POST') return json(405, { error: 'Use POST' });
  const db = admin();
  const userId = await authenticate(req, db);
  if (!userId) return json(401, { error: 'Invalid or revoked token' });

  const kind = new URL(req.url).pathname.split('/').filter(Boolean).pop() ?? '';
  const cats = kind === 'expense' ? await categoriesOf(db, userId) : [];
  const r = quickLogRow(kind, await readJson(req), Date.now(), cats);
  if (!r.ok) return json(400, { error: r.error });

  // client_id is generated by the database default (server-made, PRD F19).
  const { data, error } = await db
    .from(r.value.table)
    .insert({ ...r.value.row, user_id: userId })
    .select('client_id, date')
    .single();
  if (error) return json(500, { error: error.message });
  return json(200, { ok: true, table: r.value.table, ...data, ...r.value.row });
});
