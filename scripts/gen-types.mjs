#!/usr/bin/env node
/**
 * Writes src/types/supabase.ts from a JSON description of the public schema
 * (produced by scripts/db-types.sql against the locally migrated database).
 * Output follows the shape of `supabase gen types typescript`, so code written
 * against it works unchanged when the official generator is used:
 *   npx supabase gen types typescript --linked > src/types/supabase.ts
 * Usage: npm run gen:types
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [, , inFile, outFile] = process.argv;
const schema = JSON.parse(readFileSync(inFile, 'utf8'));

const TS = {
  uuid: 'string',
  text: 'string',
  date: 'string',
  'time without time zone': 'string',
  'timestamp with time zone': 'string',
  integer: 'number',
  bigint: 'number',
  numeric: 'number',
  boolean: 'boolean',
  jsonb: 'Json',
  json: 'Json',
};

function tsType(col) {
  if (col.type === 'ARRAY') {
    const inner = TS[col.element] ?? 'unknown';
    return `${inner}[]`;
  }
  const t = TS[col.type];
  if (!t) throw new Error(`gen-types: no mapping for ${col.type} (${col.name})`);
  return t;
}

const indent = (s, n) => s.replace(/^/gm, ' '.repeat(n));

function fields(cols, mode) {
  return cols
    .map((c) => {
      const base = tsType(c);
      const type = c.nullable ? `${base} | null` : base;
      if (mode === 'Row') return `${c.name}: ${type}`;
      if (mode === 'Update') return `${c.name}?: ${type}`;
      const optional = c.nullable || c.has_default;
      return `${c.name}${optional ? '?' : ''}: ${type}`;
    })
    .join('\n');
}

function relationships(rels) {
  if (!rels.length) return '[]';
  const items = rels.map(
    (r) => `{
  foreignKeyName: "${r.name}"
  columns: [${r.columns.map((c) => `"${c}"`).join(', ')}]
  isOneToOne: ${r.one_to_one}
  referencedRelation: "${r.ref_table}"
  referencedColumns: [${r.ref_columns.map((c) => `"${c}"`).join(', ')}]
}`,
  );
  return `[\n${indent(items.join(',\n'), 2)}\n]`;
}

const tables = schema.tables
  .map(
    (t) => `${t.name}: {
  Row: {
${indent(fields(t.columns, 'Row'), 4)}
  }
  Insert: {
${indent(fields(t.columns, 'Insert'), 4)}
  }
  Update: {
${indent(fields(t.columns, 'Update'), 4)}
  }
  Relationships: ${indent(relationships(t.relationships), 2).trimStart()}
}`,
  )
  .join('\n');

const views = schema.views
  .map(
    (v) => `${v.name}: {
  Row: {
${indent(
  fields(
    v.columns.map((c) => ({ ...c, nullable: true })),
    'Row',
  ),
  4,
)}
  }
  Relationships: []
}`,
  )
  .join('\n');

const functions = schema.functions
  .map(
    (f) => `${f.name}: {
  Args: never
  Returns: ${TS[f.returns] ?? 'unknown'}
}`,
  )
  .join('\n');

const out = `// Generated by scripts/gen-types.mjs from supabase/migrations — do not edit.
// Same shape as \`supabase gen types typescript\`. Regenerate: npm run gen:types
export type Json =
  | string
  | number
  | boolean
  | null
  | { [key: string]: Json | undefined }
  | Json[]

export type Database = {
  public: {
    Tables: {
${indent(tables, 6)}
    }
    Views: {
${indent(views, 6)}
    }
    Functions: {
${indent(functions, 6)}
    }
    Enums: {
      [_ in never]: never
    }
    CompositeTypes: {
      [_ in never]: never
    }
  }
}

type PublicSchema = Database['public']

export type Tables<T extends keyof (PublicSchema['Tables'] & PublicSchema['Views'])> =
  (PublicSchema['Tables'] & PublicSchema['Views'])[T] extends { Row: infer R } ? R : never

export type TablesInsert<T extends keyof PublicSchema['Tables']> =
  PublicSchema['Tables'][T] extends { Insert: infer I } ? I : never

export type TablesUpdate<T extends keyof PublicSchema['Tables']> =
  PublicSchema['Tables'][T] extends { Update: infer U } ? U : never
`;

writeFileSync(outFile, out);
console.log(
  `wrote ${outFile}: ${schema.tables.length} tables, ${schema.views.length} views, ${schema.functions.length} functions`,
);
